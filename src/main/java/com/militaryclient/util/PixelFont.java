    private static final int[][] ROWS = new int[G.length][7];
    static {
        for (int g = 0; g < G.length; g++)
            for (int r = 0; r < 7; r++) ROWS[g][r] = Integer.parseInt(G[g][r], 2);
    }

    private static int index(char ch) {
        ch = Character.toUpperCase(ch);
        if (ch == '\u00B0') ch = '^';
        int i = CHARS.indexOf(ch);
        return i >= 0 ? i : CHARS.indexOf('?');
    }

    /** Pixel size p: glyph is 5p wide, 7p tall; advance = 6p + extra. */
    public static int width(String s, int p, float spacing) {
        if (s.isEmpty()) return 0;
        int adv = 6 * p + Math.round(spacing * p);
        return s.length() * adv - Math.round(spacing * p) - p;
    }

    public static int height(int p) { return 7 * p; }

    public static void draw(Sink g, String s, int x, int y, int argb, int p, int mode, float spacing) {
        int adv = 6 * p + Math.round(spacing * p);
        int cx = x;
        for (int n = 0; n < s.length(); n++) {
            drawGlyph(g, index(s.charAt(n)), cx, y, argb, p, mode);
            cx += adv;
        }
    }

    private static void drawGlyph(Sink g, int gi, int x, int y, int argb, int p, int mode) {
        int[] rows = ROWS[gi];
        for (int r = 0; r < 7; r++) {
            int bits = rows[r];
            int skew = mode == 3 ? ((6 - r) * p) / 3 : 0; // italic lean for the LCD look
            int c = 0;
            while (c < 5) {
                boolean lit = (bits & (1 << (4 - c))) != 0;
                if (mode == 2 && lit && r == 3 && (c == 0 || c == 4)) lit = false;       // stencil bridges
                if (mode == 2 && lit && (r == 1 || r == 5) && c == 2 && gi < 26) lit = false;
                if (!lit) {
                    if (mode == 3 && (gi != CHARS.indexOf(' '))) {
                        g.rect(x + c * p + skew, y + r * p, p, p, (argb & 0x00FFFFFF) | 0x14000000);
                    }
                    c++;
                    continue;
                }
                int start = c;
                while (c < 5) {
                    boolean l2 = (bits & (1 << (4 - c))) != 0;
                    if (mode == 2 && l2 && r == 3 && (c == 0 || c == 4)) l2 = false;
                    if (mode == 2 && l2 && (r == 1 || r == 5) && c == 2 && gi < 26) l2 = false;
                    if (!l2) break;
                    c++;
                }
                g.rect(x + start * p + skew, y + r * p, (c - start) * p, p, argb);
            }
        }
    }

    private PixelFont() {}
